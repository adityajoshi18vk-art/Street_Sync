// Exports the compiled JanLekha ABI for consumers that must not depend on a local compile:
//   deployments/abi/JanLekha.json  (plain JSON, referenced by deployment artifacts)
//   src/lib/janlekha/abi.ts        (`as const` for typed viem reads in the Next.js app)
// `--check` fails if either committed file is out of date with the compiled artifact.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const SOURCE = "artifacts/contracts/JanLekha.sol/JanLekha.json";
const { abi } = JSON.parse(readFileSync(SOURCE, "utf8"));
const outputs = {
  "deployments/abi/JanLekha.json": `${JSON.stringify(abi, null, 2)}\n`,
  "src/lib/janlekha/abi.ts":
    `// Generated by scripts/export-abi.mjs from ${SOURCE}. Do not edit.\n` +
    `export const janLekhaAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
};

const check = process.argv.includes("--check");
let stale = false;
for (const [path, content] of Object.entries(outputs)) {
  let current = null;
  try { current = readFileSync(path, "utf8"); } catch {}
  if (current === content) continue;
  if (check) {
    console.error(`ABI out of date: ${path}. Run \`npm run contracts:build\`.`);
    stale = true;
  } else {
    mkdirSync(path.slice(0, path.lastIndexOf("/")), { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote ${path}`);
  }
}
if (stale) process.exit(1);
